#include "bignum_ctr_drbg_internal.h"

#include <stdio.h>
#include <string.h>

static const uint8_t key[32] = {
    0x60,0x3d,0xeb,0x10,0x15,0xca,0x71,0xbe,0x2b,0x73,0xae,0xf0,0x85,0x7d,0x77,0x81,
    0x1f,0x35,0x2c,0x07,0x3b,0x61,0x08,0xd7,0x2d,0x98,0x10,0xa3,0x09,0x14,0xdf,0xf4
};
static const uint8_t input[16] = {
    0x6b,0xc1,0xbe,0xe2,0x2e,0x40,0x9f,0x96,0xe9,0x3d,0x7e,0x11,0x73,0x93,0x17,0x2a
};
static const uint8_t expected[16] = {
    0xf3,0xee,0xd1,0xbd,0xb5,0xd2,0xa0,0x3c,0x06,0x4b,0x5a,0x7e,0x3d,0xb1,0x81,0xf8
};

int main(void)
{
    uint8_t expanded[240], output[16];
    bignum_ctr_drbg_aes256_expand_key(key, expanded);
    bignum_ctr_drbg_aes256_encrypt_dispatch(expanded, input, output);
    if (memcmp(output, expected, sizeof(output)) != 0) return 1;
    printf("dispatch backend=%d aesni=%d: PASS\n",
           bignum_ctr_drbg_aes256_backend(), bignum_ctr_drbg_aes256_runtime_has_aesni());
    return 0;
}
